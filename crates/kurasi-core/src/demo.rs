fn stamp(base: chrono::DateTime<chrono::Local>, minutes: i64) -> String {
    (base + chrono::Duration::minutes(minutes)).format("%Y-%m-%dT%H:%M:%S").to_string()
}

fn now_local() -> chrono::DateTime<chrono::Local> {
    chrono::Local::now().with_nanosecond(0).unwrap_or_else(chrono::Local::now)
}

use chrono::Timelike;

/// Writes every sample file into an empty folder.
pub fn write_files(folder: &Path) -> Result<()> {
    let colour = default_settings().get("hl_colour").and_then(|v| v.as_str()).unwrap_or("#ffd84a").to_string();
    let base = now_local() - chrono::Duration::days(9);
    for (i, work) in works().iter().enumerate() {
        let path = folder.join(work.path);
        let mut doc = make_pdf(&path, work.title, work.authors, work.year, work.pub_, work.vol, work.body, &[], true, work.path)?;
        if let Some(original) = work.translation_of {
            make_pdf(
                &folder.join(original),
                work.title,
                work.authors,
                work.year,
                work.pub_,
                work.vol,
                work.body,
                &["Erstdruck in zwei Teilen, Band 20 und 21."],
                true,
                &format!("{}:de", work.path),
            )?;
            doc.text_centered(0, 90.0, 10.0, "The Protestant ethic and the spirit of capitalism. English translated copy.");
        }
        for (j, h) in work.hl.iter().enumerate() {
            let sentence = page_sentences(work.path, h.page, 12)[h.idx].clone();
            let (quads, _) = doc
                .find_quote(h.page, &sentence)?
                .ok_or_else(|| Error::Other(format!("sample sentence not found on page {} of {}", h.page, work.path)))?;
            let tags: Vec<String> = h.tags.iter().map(|t| t.to_string()).collect();
            doc.add_highlight(&NewAnnot {
                page: h.page,
                quads,
                author: h.author.to_string(),
                contents: compose(h.analysis, &tags),
                colour: colour.clone(),
                kind: "text".into(),
                created: Some(stamp(base, (i * 600 + j * 37) as i64)),
            })?;
        }
        doc.write_to(&path)?;
    }
    for item in INBOX {
        make_pdf(&folder.join(item.path), item.title, &[item.author], item.year, item.pub_, "", item.body, &[], false, item.path)?;
    }
    for note in NOTES {
        let p = folder.join(note.path);
        if let Some(parent) = p.parent() {
            std::fs::create_dir_all(parent)?;
        }
        std::fs::write(&p, note.text.replace("\r\n", "\n"))?;
    }
    exhibit_division(&folder.join(EXHIBITS[0].0))?;
    let mut years: Vec<i64> = works().iter().filter_map(|w| w.year.parse().ok()).collect();
    years.extend(INBOX.iter().filter_map(|i| i.year.parse::<i64>().ok()));
    exhibit_timeline(&folder.join(EXHIBITS[1].0), &years)?;
    Ok(())
}

fn wipe_database(path: &Path) -> Result<()> {
    let db = crate::Db::open(path)?;
    db.tx(|c| {
        for table in ["setting", "category", "reference", "reference_author", "reference_category", "file", "highlight", "trash", "ai_log", "change"] {
            c.execute(&format!("DELETE FROM {}", table), [])?;
        }
        c.execute("INSERT INTO category(id,parent_id,name,sort) VALUES(1,NULL,'Uncategorized',0)", [])?;
        Ok(())
    })
}

/// Rebuilds the sample project from scratch (folder, database and registry entry) and returns
/// its registry entry. Calling it again resets the sample.
pub fn build(paths: &AppPaths) -> Result<ProjectInfo> {
    let folder = paths.demo_dir();
    if folder.is_dir() {
        std::fs::remove_dir_all(&folder)
            .map_err(|_| Error::conflict("A sample file is open in another program. Close it and reset the sample again."))?;
    }
    std::fs::create_dir_all(&folder)?;
    let db_dir = paths.root.join("projects").join(DEMO_ID);
    if db_dir.exists() && std::fs::remove_dir_all(&db_dir).is_err() {
        wipe_database(&db_dir.join("kurasi.sqlite"))?;
    }
    write_files(&folder)?;
    let entry = paths.register(Some(DEMO_NAME), &folder, Some(DEMO_ID), true)?;
    let project = Project::open_entry(paths, &entry, Some(DEMO_NAME), Some(false), Arc::new(SimplePdfBackend))?;
    populate(&project)?;
    Ok(entry)
}

/// Opens the sample project (built when absent). The backend is the built-in simple reader.
pub fn open(paths: &AppPaths) -> Result<Project> {
    let built = paths.demo_dir().is_dir() && paths.resolve(DEMO_ID).is_some();
    if !built {
        build(paths)?;
    }
    let entry = paths.resolve(DEMO_ID).ok_or_else(|| Error::not_found("The sample project is not registered."))?;
    Project::open_entry(paths, &entry, None, None, Arc::new(SimplePdfBackend))
}

fn populate(project: &Project) -> Result<()> {
    project.set_defer_sidecar(true);
    for path in CATEGORIES {
        project.ensure_category_path(path)?;
    }
    project.scan_as(ScanMode::Incremental, Origin::Scan, |_| {})?;
    let base = now_local() - chrono::Duration::days(12);
    let ref_for = |relpath: &str| -> Result<String> {
        let rel = relpath.replace('/', "\\");
        project
            .db()
            .with(|c| crate::db::file_by_relpath(c, &rel))?
            .map(|f| f.ref_id)
            .ok_or_else(|| Error::Other(format!("sample file {} was not scanned", relpath)))
    };
    let set_times = |rid: &str, created: &str, updated: &str| -> Result<()> {
        project.db().with(|c| {
            c.execute("UPDATE reference SET created_at=?, updated_at=? WHERE id=?", rusqlite::params![created, updated, rid])?;
            Ok(())
        })
    };
    let all_works = works();
    for (i, work) in all_works.iter().enumerate() {
        let rid = ref_for(work.path)?;
        let mut fields = serde_json::Map::new();
        for (k, v) in [
            ("title", work.title), ("year", work.year), ("pub", work.pub_), ("kind", work.kind), ("lang", work.lang),
            ("usability", work.usability), ("vol", work.vol), ("pages_range", work.pages_range), ("status", work.status),
        ] {
            fields.insert(k.into(), json!(v));
        }
        let patch = ReferencePatch {
            fields,
            authors: Some(work.authors.iter().map(|a| a.to_string()).collect()),
            categories: Some(work.cats.iter().map(|c| c.to_string()).collect()),
        };
        project.update_reference(&rid, &patch, Origin::Scan, "Verified")?;
        set_times(&rid, &stamp(base, (i * 720) as i64), &stamp(base, (i * 720 + 2000) as i64))?;
        let hls = project.highlights(&HighlightFilter { ref_id: Some(rid.clone()), ..Default::default() })?;
        for h in &work.hl {
            let text: String = h.analysis.lines().next().unwrap_or("").chars().take(30).collect();
            let hit = hls.iter().find(|x| x.page == Some(h.page as i64) && x.analysis.starts_with(&text));
            let hit = match hit {
                Some(x) => x,
                None => continue,
            };
            if let Some(reason) = h.delete {
                project.propose_delete(&hit.id, reason, Origin::Scan)?;
            }
            if !h.suggest_tags.is_empty() {
                project.suggest_tags(&hit.id, &h.suggest_tags.iter().map(|t| t.to_string()).collect::<Vec<_>>(), Origin::Scan)?;
            }
        }
    }
    let mut offset = (all_works.len() * 720) as i64;
    for (k, note) in NOTES.iter().enumerate() {
        let rid = ref_for(note.path)?;
        let mut fields = serde_json::Map::new();
        for (key, v) in [("title", note.title), ("kind", "Working note"), ("year", "2026"), ("lang", "en"), ("usability", "Full text"), ("status", "Verified")] {
            fields.insert(key.into(), json!(v));
        }
        project.update_reference(
            &rid,
            &ReferencePatch { fields, authors: Some(vec!["Kurasi sample".into()]), categories: Some(vec!["Notes".into()]) },
            Origin::Scan,
            "Verified",
        )?;
        set_times(&rid, &stamp(base, offset + k as i64 * 300), &stamp(base, offset + k as i64 * 300 + 900))?;
        let fid = project.db().with(|c| {
            c.query_row("SELECT id FROM file WHERE ref_id=?", [&rid], |r| r.get::<_, String>(0)).map_err(Error::from)
        })?;
        let writer = if note.author == AI {
            Writer { author: AI.into(), origin: "ai".into(), change_origin: Origin::Scan }
        } else {
            Writer { author: YOU.into(), origin: "human".into(), change_origin: Origin::Scan }
        };
        project.add_highlight(
            &NewHighlight {
                file_id: fid,
                kind: Some("md".into()),
                anchor: Some(json!({"text": note.quote, "occurrence": 0})),
                verbatim: Some(note.quote.into()),
                analysis: Some(note.analysis.into()),
                tags: Some(note.tags.iter().map(|t| t.to_string()).collect()),
                ..Default::default()
            },
            &writer,
        )?;
    }
    offset += (NOTES.len() * 300) as i64;
    for (k, (path, title)) in EXHIBITS.iter().enumerate() {
        let rid = ref_for(path)?;
        let mut fields = serde_json::Map::new();
        for (key, v) in [("title", *title), ("kind", "Exhibit"), ("year", "2026"), ("lang", "en"), ("usability", "Full text"), ("status", "Verified")] {
            fields.insert(key.into(), json!(v));
        }
        project.update_reference(
            &rid,
            &ReferencePatch { fields, authors: Some(vec!["Kurasi sample".into()]), categories: Some(vec!["Exhibits".into()]) },
            Origin::Scan,
            "Verified",
        )?;
        set_times(&rid, &stamp(base, offset + k as i64 * 300), &stamp(base, offset + k as i64 * 300 + 600))?;
        if k == 0 {
            let fid = project.db().with(|c| {
                c.query_row("SELECT id FROM file WHERE ref_id=?", [&rid], |r| r.get::<_, String>(0)).map_err(Error::from)
            })?;
            project.add_highlight(
                &NewHighlight {
                    file_id: fid,
                    kind: Some("region".into()),
                    quads: Some(vec![vec![0.52, 0.17, 0.42, 0.68]]),
                    verbatim: Some("Output per worker rises with each further split of the task (illustrative numbers)".into()),
                    analysis: Some("(I) The steep rise on the right is the effect the sample notes discuss.".into()),
                    tags: Some(vec!["division-of-labour".into(), "efficiency".into()]),
                    ..Default::default()
                },
                &Writer { author: YOU.into(), origin: "human".into(), change_origin: Origin::Scan },
            )?;
        }
    }
    let newest = now_local() - chrono::Duration::hours(3);
    for (k, item) in INBOX.iter().enumerate() {
        let rid = ref_for(item.path)?;
        let t = stamp(newest, k as i64 * 20);
        set_times(&rid, &t, &t)?;
    }
    let log_base = now_local() - chrono::Duration::days(2);
    for (k, (tool, purpose, result)) in AI_LOG.iter().enumerate() {
        project.log_ai(tool, "claude-code", purpose, &json!({"sample": true}), result, Some(&stamp(log_base, k as i64 * 95)))?;
    }
    {
        let _g = project.write_lock().acquire()?;
        project.db().tx(|c| {
            c.execute("DELETE FROM change", [])?;
            crate::db::log_change(c, "Sample project built", &[], "scan")?;
            Ok(())
        })?;
    }
    project.set_defer_sidecar(false);
    project.sidecar_write();
    Ok(())
}
