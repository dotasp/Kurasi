fn seed_hash(seed: &str) -> u64 {
    // FNV-1a: stable across runs and platforms.
    let mut h: u64 = 0xcbf29ce484222325;
    for b in seed.bytes() {
        h ^= b as u64;
        h = h.wrapping_mul(0x100000001b3);
    }
    h
}

/// Twelve distinct sentences for one page, chosen by a seeded shuffle.
pub fn page_sentences(seed: &str, page: usize, count: usize) -> Vec<String> {
    let mut state = seed_hash(&format!("{}:{}", seed, page)) | 1;
    let mut pool: Vec<&str> = SENTENCES.to_vec();
    let mut out = Vec::new();
    for _ in 0..count.min(pool.len()) {
        // xorshift64
        state ^= state << 13;
        state ^= state >> 7;
        state ^= state << 17;
        let i = (state % pool.len() as u64) as usize;
        out.push(pool.remove(i).to_string());
    }
    out
}

fn title_page(doc: &mut SimpleDoc, page: usize, title: &str, authors: &[&str], pub_: &str, vol: &str, year: &str, lines: &[&str]) {
    let mut y = 150.0;
    for line in crate::simplepdf::wrap(title, 44) {
        doc.text_centered(page, y, 16.0, &line);
        y += 24.0;
    }
    y += 10.0;
    doc.text_centered(page, y, 12.0, &authors.join(", "));
    y += 22.0;
    let mut pub_line: Vec<String> = Vec::new();
    if !pub_.is_empty() {
        pub_line.push(pub_.to_string());
    }
    if !vol.is_empty() {
        pub_line.push(format!("vol. {}", vol));
    }
    if !year.is_empty() {
        pub_line.push(year.to_string());
    }
    doc.text_centered(page, y, 11.0, &pub_line.join(", "));
    y += 40.0;
    for line in lines {
        doc.text_centered(page, y, 11.0, line);
        y += 18.0;
    }
    doc.text_centered(page, 760.0, 9.0, SAMPLE_LINE);
}

fn body_page(doc: &mut SimpleDoc, page: usize, header: &str, sentences: &[String]) {
    doc.text(page, 72.0, 52.0, 8.0, header);
    doc.paragraphs(page, 72.0, 84.0, 451.0, 10.0, sentences);
}

fn make_pdf(path: &Path, title: &str, authors: &[&str], year: &str, pub_: &str, vol: &str, body: usize, title_lines: &[&str], metadata: bool, seed: &str) -> Result<SimpleDoc> {
    let mut doc = SimpleDoc::new();
    let p = doc.add_page();
    title_page(&mut doc, p, title, authors, pub_, vol, year, title_lines);
    let surname = authors.first().map(|a| a.split(',').next().unwrap_or("").trim().to_string()).unwrap_or_default();
    let header = format!("{} ({}). Sample text.", surname, year);
    for page_no in 2..body + 2 {
        let p = doc.add_page();
        body_page(&mut doc, p, &format!("{} Page {}.", header, page_no), &page_sentences(seed, page_no, 12));
    }
    if metadata {
        doc.title = title.to_string();
        doc.author = authors.join("; ");
    }
    doc.write_to(path)?;
    Ok(doc)
}

