fn fill_rect(img: &mut image::RgbImage, x0: i64, y0: i64, x1: i64, y1: i64, colour: [u8; 3]) {
    let (w, h) = (img.width() as i64, img.height() as i64);
    for y in y0.max(0)..y1.min(h) {
        for x in x0.max(0)..x1.min(w) {
            img.put_pixel(x as u32, y as u32, image::Rgb(colour));
        }
    }
}

fn save_png(img: &image::RgbImage, path: &Path) -> Result<()> {
    if let Some(parent) = path.parent() {
        std::fs::create_dir_all(parent)?;
    }
    img.save(path).map_err(|e| Error::Other(format!("PNG write failed: {}", e)))
}

const INK: [u8; 3] = [29, 36, 51];
const AXIS: [u8; 3] = [85, 85, 85];
const BAR: [u8; 3] = [59, 111, 182];
const ACCENT: [u8; 3] = [180, 70, 43];

/// Exhibit 1: bars of output per worker by the number of operations (illustrative numbers).
pub fn exhibit_division(path: &Path) -> Result<()> {
    let (w, h) = (1600i64, 1000i64);
    let mut img = image::RgbImage::from_pixel(w as u32, h as u32, image::Rgb([255, 255, 255]));
    // Title band and the "Illustrative numbers" accent mark.
    fill_rect(&mut img, 70, 50, 900, 58, INK);
    fill_rect(&mut img, 70, 112, 330, 118, ACCENT);
    let data = [20.0, 60.0, 400.0, 1800.0, 4800.0];
    let (left, right, top, bottom) = (200i64, w - 90, 200i64, h - 140);
    fill_rect(&mut img, left, top, left + 3, bottom, AXIS);
    fill_rect(&mut img, left, bottom, right, bottom + 3, AXIS);
    let peak = 4800.0;
    let bw = (right - left) as f64 / data.len() as f64;
    for (i, v) in data.iter().enumerate() {
        let x0 = left as f64 + i as f64 * bw + bw * 0.18;
        let x1 = left as f64 + (i + 1) as f64 * bw - bw * 0.18;
        let y0 = bottom as f64 - (bottom - top - 40) as f64 * v / peak;
        fill_rect(&mut img, x0 as i64, y0 as i64, x1 as i64, bottom - 2, BAR);
        fill_rect(&mut img, x0 as i64, bottom + 18, x1 as i64, bottom + 24, INK);
    }
    fill_rect(&mut img, 70, h - 70, 700, h - 64, AXIS);
    save_png(&img, path)
}

/// Exhibit 2: a timeline of the publication years above.
pub fn exhibit_timeline(path: &Path, years: &[i64]) -> Result<()> {
    let (w, h) = (1600i64, 1000i64);
    let mut img = image::RgbImage::from_pixel(w as u32, h as u32, image::Rgb([255, 255, 255]));
    fill_rect(&mut img, 70, 50, 900, 58, INK);
    let (y0, x_left, x_right) = (520i64, 110i64, w - 110);
    let (lo, hi) = (1770.0, 1925.0);
    fill_rect(&mut img, x_left, y0 - 2, x_right, y0 + 2, AXIS);
    let mut year = 1775;
    while year <= 1925 {
        let x = x_left as f64 + (x_right - x_left) as f64 * (year as f64 - lo) / (hi - lo);
        fill_rect(&mut img, x as i64 - 1, y0 - 10, x as i64 + 2, y0 + 10, AXIS);
        fill_rect(&mut img, x as i64 - 32, y0 + 22, x as i64 + 32, y0 + 26, AXIS);
        year += 25;
    }
    let mut sorted = years.to_vec();
    sorted.sort();
    for (i, year) in sorted.iter().enumerate() {
        let x = x_left as f64 + (x_right - x_left) as f64 * (*year as f64 - lo) / (hi - lo);
        let up = i % 2 == 0;
        let level = 60 + 70 * ((i / 2) % 4) as i64;
        let ty = if up { y0 - level - 40 } else { y0 + level + 30 };
        let (a, b) = if up { (ty + 40, y0) } else { (y0, ty) };
        fill_rect(&mut img, x as i64 - 1, a, x as i64 + 1, b, [154, 164, 181]);
        fill_rect(&mut img, x as i64 - 60, ty, x as i64 + 100, ty + 6, INK);
        fill_rect(&mut img, x as i64 - 9, y0 - 9, x as i64 + 9, y0 + 9, BAR);
    }
    fill_rect(&mut img, 70, h - 70, 500, h - 64, AXIS);
    save_png(&img, path)
}

