/// One planned PDF highlight: body page, sentence index on that page, author, analysis, tags,
/// and an optional review flow (`delete` reason or `suggest_tags`).
struct Hl {
    page: usize,
    idx: usize,
    author: &'static str,
    analysis: &'static str,
    tags: &'static [&'static str],
    delete: Option<&'static str>,
    suggest_tags: &'static [&'static str],
}

const fn hl(page: usize, idx: usize, author: &'static str, analysis: &'static str, tags: &'static [&'static str]) -> Hl {
    Hl { page, idx, author, analysis, tags, delete: None, suggest_tags: &[] }
}

